# {% icon "camera" 18 %} -> draws that icon.
@register.simple_tag
def icon(name, size=18, cls=""):
    return mark_safe(
        f'<svg class="i {cls}" width="{size}" height="{size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" '
        f'stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">{ICONS.get(name, ICONS["leaf"])}</svg>'
    )


# {% status c %} -> coloured status badge for a complaint.
@register.simple_tag
def status(c, solid=False):
    return format_html('<span class="badge t-{}{}"><i class="dot"></i>{}</span>', c.tone, " solid" if solid else "", c.get_status_display())


# {% avatar user %} -> round circle with the user's initials.
@register.simple_tag
def avatar(user, cls=""):
    return format_html('<span class="avatar {}" style="--h:{}">{}</span>', cls, user.hue, user.initials)


# {% stars 4 %} -> 4 filled stars out of 5.
@register.simple_tag
def stars(value, size=15):
    value = int(round(value or 0))
    out = "".join(
        f'<svg class="{"on" if i <= value else ""}" width="{size}" height="{size}" viewBox="0 0 24 24">{ICONS["star"]}</svg>'
        for i in range(1, 6)
    )
    return mark_safe(f'<span class="stars" title="{value}/5">{out}</span>')


# {% active 'panel:dashboard' %} -> prints 'active' if that is the current page (menu highlight).
@register.simple_tag(takes_context=True)
def active(context, *names):
    m = context["request"].resolver_match
    cur = f"{m.namespace}:{m.url_name}" if m else ""
    return "active" if any(cur == n or (n.endswith(":*") and cur.startswith(n[:-1])) for n in names) else ""


# Filters: dict|get:key and percentage.
@register.filter
def get(d, key):
    return d.get(key, 0) if d else 0


@register.filter
def pct(value, total):
    try:
        return round(float(value) / float(total) * 100) if float(total) else 0
    except (TypeError, ValueError):
        return 0
